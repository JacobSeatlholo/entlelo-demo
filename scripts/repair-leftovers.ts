/**
 * Retries strings that equal their English source (length > 60) in
 * non-English dictionaries — the residue of 429 rate-limit fallbacks.
 */
import fs from "node:fs";
import ZAI from "z-ai-web-dev-sdk";
import { en, type Dict } from "../src/lib/i18n/en";

const LANG_NAMES: Record<string, string> = {
  af: "Afrikaans", zu: "isiZulu", xh: "isiXhosa", st: "Sesotho", tn: "Setswana",
  nso: "Sepedi", ss: "siSwati", ve: "Tshivenḓa", ts: "Xitsonga", nr: "isiNdebele",
};

function isProperOnly(s: string): boolean {
  // strings made purely of proper nouns/numbers/labels we keep by design
  return !/[a-zäöüéèáàñḓṱḽš]{4,}/.test(s);
}

function collect(source: unknown, out: unknown, trail: string, bad: { trail: string; en: string }[]): void {
  if (typeof source === "string") {
    const cur = typeof out === "string" ? out : "";
    if (source.length > 60 && cur === source && !isProperOnly(source)) {
      bad.push({ trail, en: source });
    }
    return;
  }
  if (Array.isArray(source)) {
    source.forEach((s, i) => collect(s, (out as unknown[])?.[i], `${trail}[${i}]`, bad));
    return;
  }
  if (source && typeof source === "object") {
    for (const [k, v] of Object.entries(source as Record<string, unknown>)) {
      collect(v, (out as Record<string, unknown>)?.[k], `${trail}.${k}`, bad);
    }
  }
}

function getIn(obj: unknown, dotted: string): unknown {
  let node: unknown = obj;
  for (const part of dotted.split(".")) {
    if (node === null || typeof node !== "object") return undefined;
    node = (node as Record<string, unknown>)[part];
  }
  return node;
}
function setIn(obj: Record<string, unknown>, dotted: string, value: unknown): void {
  const parts = dotted.split(".");
  let node: Record<string, unknown> = obj;
  for (const part of parts.slice(0, -1)) node = node[part] as Record<string, unknown>;
  node[parts[parts.length - 1]] = value;
}

function repScore(text: string): number {
  const words = text.toLowerCase().split(/\s+/).filter(Boolean);
  const grams = new Map<string, number>();
  for (let n = 3; n <= 5; n++)
    for (let i = 0; i + n <= words.length; i++) {
      const g = words.slice(i, i + n).join(" ");
      grams.set(g, (grams.get(g) ?? 0) + 1);
    }
  return grams.size ? Math.max(...grams.values()) : 0;
}

function persist(dicts: Record<string, Dict>, fixed: number): void {
  const header = [
    "// AUTO-GENERATED by scripts/gen-translations.ts + curated patches — do not edit by hand.",
    "// English source of truth lives in src/lib/i18n/en.ts.",
    "",
    'import type { LangCode } from "./config";',
    'import { en, type Dict } from "./en";',
    "",
  ].join("\n");
  const order = ["af", "zu", "xh", "st", "tn", "nso", "ss", "ve", "ts", "nr"];
  const blocks = order.map((c) => `export const ${c}: Dict = ${JSON.stringify(dicts[c], null, 2)};\n`).join("\n");
  const exportLine = `export const dictionaries: Record<LangCode, Dict> = {\n  en,\n  ${order.join(",\n  ")},\n};\n`;
  fs.writeFileSync("src/lib/i18n/translations.ts", `${header}${blocks}\n${exportLine}`);
  console.log(`[persist] saved (${fixed} fixed so far)`);
}

async function main() {
  const zai = await ZAI.create();
  const mod = await import("../src/lib/i18n/translations");
  const dicts = mod.dictionaries as unknown as Record<string, Dict>;
  let fixed = 0;

  for (const code of Object.keys(LANG_NAMES)) {
    const bad: { trail: string; en: string }[] = [];
    collect(en, dicts[code], code, bad);
    if (!bad.length) continue;
    console.log(`${code}: ${bad.length} English leftover(s)`);
    for (const item of bad) {
      let done: string | null = null;
      for (let attempt = 1; attempt <= 5 && !done; attempt++) {
        try {
          const completion = await zai.chat.completions.create({
            messages: [
              { role: "assistant", content: "You are a senior South African translator. Translate ONE string. Never repeat phrases. Output only the translated text." },
              { role: "user", content: `Translate into ${LANG_NAMES[code]} (${code}). Keep brand names (Entlelo, Clear Vu, SANS, CIDB 6) and places. Same length and tone.\n\nENGLISH:\n${item.en}` },
            ],
            thinking: { type: "disabled" },
          });
          const out = (completion.choices[0]?.message?.content ?? "").trim();
          if (out.length >= 40 && repScore(out) < 3 && out !== item.en) done = out;
          else console.error(`  [${code}] ${item.trail} attempt ${attempt}: rejected`);
        } catch (err) {
          const msg = String(err);
          console.error(`  [${code}] ${item.trail} attempt ${attempt}: ${msg.slice(0, 60)}`);
          if (msg.includes("429")) await new Promise((r) => setTimeout(r, 20000));
        }
      }
      if (done) {
        setIn(dicts[code] as unknown as Record<string, unknown>, item.trail.split(".").slice(1).join("."), done);
        fixed += 1;
        console.log(`  [${code}] ${item.trail} FIXED`);
      } else {
        console.warn(`  [${code}] ${item.trail} kept in English`);
      }
    }
    persist(dicts, fixed);
  }

  persist(dicts, fixed);
  console.log(`\nFixed ${fixed}.`);
}
main().catch((e) => { console.error(e); process.exit(1); });
