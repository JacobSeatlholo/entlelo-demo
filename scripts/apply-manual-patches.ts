function setIn(obj: Record<string, unknown>, dotted: string, value: string): void {
  const parts = dotted.split(".");
  let node: Record<string, unknown> = obj;
  for (const part of parts.slice(0, -1)) {
    const next = node[part];
    if (next === null || typeof next !== "object") throw new Error(`Missing parent for ${dotted}`);
    node = next as Record<string, unknown>;
  }
  node[parts[parts.length - 1]] = value;
}

async function main() {
  const mod = await import("../src/lib/i18n/translations");
  const dicts = mod.dictionaries as unknown as Record<string, Dict>;

  let applied = 0;
  for (const [code, patches] of Object.entries(PATCHES)) {
    const dict = JSON.parse(JSON.stringify(dicts[code])) as Dict;
    const root = dict as unknown as Record<string, unknown>;
    for (const [dotted, value] of Object.entries(patches)) {
      setIn(root, dotted, value);
      applied += 1;
    }
    dicts[code] = dict;
  }
  console.log(`Applied ${applied} curated patches across ${Object.keys(PATCHES).length} languages.`);

  // Rewrite translations.ts
  const header = [
    "// AUTO-GENERATED by scripts/gen-translations.ts + curated patches — do not edit by hand.",
    "// English source of truth lives in src/lib/i18n/en.ts.",
    "",
    'import type { LangCode } from "./config";',
    'import { en, type Dict } from "./en";',
    "",
  ].join("\n");

  const order = ["af", "zu", "xh", "st", "tn", "nso", "ss", "ve", "ts", "nr"];
  const blocks = order
    .map((c) => `export const ${c}: Dict = ${JSON.stringify(dicts[c], null, 2)};\n`)
    .join("\n");
  const exportLine = `export const dictionaries: Record<LangCode, Dict> = {\n  en,\n  ${order.join(",\n  ")},\n};\n`;
  fs.writeFileSync("src/lib/i18n/translations.ts", `${header}${blocks}\n${exportLine}`);
  console.log("Rewrote translations.ts.");
}

main().catch((err) => {
  console.error("Patch application failed:", err);
  process.exit(1);
});
